s=0.5;
nd=20;
na=10;
m=4;
nc=20;
sphere_diameter=40;
sphere_radius=sphere_diameter/2;
nx=100;
ny=100;
nz=100;
itheta=90;
iphi=0;
ialpha=0;
ix=-sind(itheta)*cosd(iphi);
iy=-sind(itheta)*sind(iphi);
iz=-cosd(itheta);
ni=2*ceil((nx/2-nc+.5)*abs(ix)+(ny/2-nc+.5)*abs(iy)+(nz/2-nc+.5)*abs(iz))+2*na;
nt=floor(ni/s*5);
ei=zeros(1,ni+1);
hi=zeros(1,ni);
zei=0;
zhi=0;
etheta=[cosd(itheta)*cosd(iphi),cosd(itheta)*sind(iphi),-sind(itheta)];
ephi=[-sind(iphi),cosd(iphi),0];
ie=etheta*cosd(ialpha)+ephi*sind(ialpha);
ih=cross([ix,iy,iz],ie);
iex=ie(1);
iey=ie(2);
iez=ie(3);
ihx=ih(1);
ihy=ih(2);
ihz=ih(3);
cyex=permute(-nx/2+nc+.5:nx/2-nc-.5,[2,3,1])*ix+(ny/2-nc)*permute([-1,1],[1,2,3])*iy+permute(-nz/2+nc:nz/2-nc,[3,1,2])*iz+ni/2+1;
czex=permute(-nx/2+nc+.5:nx/2-nc-.5,[2,3,1])*ix+(nz/2-nc)*permute([-1,1],[3,1,2])*iz+permute(-ny/2+nc:ny/2-nc,[1,2,3])*iy+ni/2+1;
czey=permute(-ny/2+nc+.5:ny/2-nc-.5,[1,2,3])*iy+(nz/2-nc)*permute([-1,1],[3,1,2])*iz+permute(-nx/2+nc:nx/2-nc,[2,3,1])*ix+ni/2+1;
cxey=permute(-ny/2+nc+.5:ny/2-nc-.5,[1,2,3])*iy+(nx/2-nc)*permute([-1,1],[2,3,1])*ix+permute(-nz/2+nc:nz/2-nc,[3,1,2])*iz+ni/2+1;
cxez=permute(-nz/2+nc+.5:nz/2-nc-.5,[3,1,2])*iz+(nx/2-nc)*permute([-1,1],[2,3,1])*ix+permute(-ny/2+nc:ny/2-nc,[1,2,3])*iy+ni/2+1;
cyez=permute(-nz/2+nc+.5:nz/2-nc-.5,[3,1,2])*iz+(ny/2-nc)*permute([-1,1],[1,2,3])*iy+permute(-nx/2+nc:nx/2-nc,[2,3,1])*ix+ni/2+1;
cyhx=permute(-nx/2+nc:nx/2-nc,[2,3,1])*ix+(ny/2-nc+.5)*permute([-1,1],[1,2,3])*iy+permute(-nz/2+nc+.5:nz/2-nc-.5,[3,1,2])*iz+ni/2+.5;
czhx=permute(-nx/2+nc:nx/2-nc,[2,3,1])*ix+(nz/2-nc+.5)*permute([-1,1],[3,1,2])*iz+permute(-ny/2+nc+.5:ny/2-nc-.5,[1,2,3])*iy+ni/2+.5;
czhy=permute(-ny/2+nc:ny/2-nc,[1,2,3])*iy+(nz/2-nc+.5)*permute([-1,1],[3,1,2])*iz+permute(-nx/2+nc+.5:nx/2-nc-.5,[2,3,1])*ix+ni/2+.5;
cxhy=permute(-ny/2+nc:ny/2-nc,[1,2,3])*iy+(nx/2-nc+.5)*permute([-1,1],[2,3,1])*ix+permute(-nz/2+nc+.5:nz/2-nc-.5,[3,1,2])*iz+ni/2+.5;
cxhz=permute(-nz/2+nc:nz/2-nc,[3,1,2])*iz+(nx/2-nc+.5)*permute([-1,1],[2,3,1])*ix+permute(-ny/2+nc+.5:ny/2-nc-.5,[1,2,3])*iy+ni/2+.5;
cyhz=permute(-nz/2+nc:nz/2-nc,[3,1,2])*iz+(ny/2-nc+.5)*permute([-1,1],[1,2,3])*iy+permute(-nx/2+nc+.5:nx/2-nc-.5,[2,3,1])*ix+ni/2+.5;
cyex1=mod(cyex,1);
czex1=mod(czex,1);
czey1=mod(czey,1);
cxey1=mod(cxey,1);
cxez1=mod(cxez,1);
cyez1=mod(cyez,1);
cyhx1=mod(cyhx,1);
czhx1=mod(czhx,1);
czhy1=mod(czhy,1);
cxhy1=mod(cxhy,1);
cxhz1=mod(cxhz,1);
cyhz1=mod(cyhz,1);
cyex=floor(cyex);
czex=floor(czex);
czey=floor(czey);
cxey=floor(cxey);
cxez=floor(cxez);
cyez=floor(cyez);
cyhx=floor(cyhx);
czhx=floor(czhx);
czhy=floor(czhy);
cxhy=floor(cxhy);
cxhz=floor(cxhz);
cyhz=floor(cyhz);
ex=zeros(nx,ny+1,nz+1);
ey=zeros(nx+1,ny,nz+1);
ez=zeros(nx+1,ny+1,nz);
hx=0;
hy=0;
hz=0;
xhy=0;
yhx=0;
yhz=0;
zhy=0;
zhx=0;
xhz=0;
xey=0;
yex=0;
yez=0;
zey=0;
zex=0;
xez=0;

[x_ex,y_ex,z_ex]=ndgrid(-nx/2+.5:nx/2-.5,-ny/2:ny/2,-nz/2:nz/2);
[x_ey,y_ey,z_ey]=ndgrid(-nx/2:nx/2,-ny/2+.5:ny/2-.5,-nz/2:nz/2);
[x_ez,y_ez,z_ez]=ndgrid(-nx/2:nx/2,-ny/2:ny/2,-nz/2+.5:nz/2-.5);
mask_ex=x_ex.^2+y_ex.^2+z_ex.^2<=sphere_radius^2;
mask_ey=x_ey.^2+y_ey.^2+z_ey.^2<=sphere_radius^2;
mask_ez=x_ez.^2+y_ez.^2+z_ez.^2<=sphere_radius^2;

xe=4/5*s*(m+1)*((1:na-1)/na).^m;
xm=4/5*s*(m+1)*((.5:na-.5)/na).^m;
aei=exp(-xe);
bei=1-aei;
ami=exp(-xm);
bmi=1-ami;
ae=[fliplr(aei),aei];
be=[fliplr(bei),bei];
am=[fliplr(ami),ami];
bm=[fliplr(bmi),bmi];
hfig=imagesc(0,0,ez(:,:,nz/2+1),1*[-1,1]);
axis equal tight;
colorbar;
for n=1:1000
    hi=hi-s*diff(ei);
    hi(end-na+1:end)=hi(end-na+1:end)-s*zei;
    zhi=aei.*zhi-bei.*diff(hi(end-na+1:end));
    hx=hx-s*(diff(ez(2:end-1,:,:),1,2)-diff(ey(2:end-1,:,:),1,3));
    hx(:,[1:na,end-na+1:end],:)=hx(:,[1:na,end-na+1:end],:)-s*yez;
    hx(:,:,[1:na,end-na+1:end])=hx(:,:,[1:na,end-na+1:end])+s*zey;
    hx(nc:end-nc+1,[nc,end-nc+1],nc+1:end-nc)=hx(nc:end-nc+1,[nc,end-nc+1],nc+1:end-nc)-s*permute([-1,1],[1,2,3]).*(ei(cyez).*(1-cyez1)+ei(cyez+1).*cyez1)*iez;
    hx(nc:end-nc+1,nc+1:end-nc,[nc,end-nc+1])=hx(nc:end-nc+1,nc+1:end-nc,[nc,end-nc+1])+s*permute([-1,1],[3,1,2]).*(ei(czey).*(1-czey1)+ei(czey+1).*czey1)*iey;
    yhx=permute(ae,[1,2,3]).*yhx-permute(be,[1,2,3]).*cat(2,diff(hx(:,1:na,:),1,2),diff(hx(:,end-na+1:end,:),1,2));
    zhx=permute(ae,[3,1,2]).*zhx-permute(be,[3,1,2]).*cat(3,diff(hx(:,:,1:na),1,3),diff(hx(:,:,end-na+1:end),1,3));
    hy=hy-s*(diff(ex(:,2:end-1,:),1,3)-diff(ez(:,2:end-1,:),1,1));
    hy(:,:,[1:na,end-na+1:end])=hy(:,:,[1:na,end-na+1:end])-s*zex;
    hy([1:na,end-na+1:end],:,:)=hy([1:na,end-na+1:end],:,:)+s*xez;
    hy(nc+1:end-nc,nc:end-nc+1,[nc,end-nc+1])=hy(nc+1:end-nc,nc:end-nc+1,[nc,end-nc+1])-s*permute([-1,1],[3,1,2]).*(ei(czex).*(1-czex1)+ei(czex+1).*czex1)*iex;
    hy([nc,end-nc+1],nc:end-nc+1,nc+1:end-nc)=hy([nc,end-nc+1],nc:end-nc+1,nc+1:end-nc)+s*permute([-1,1],[2,3,1]).*(ei(cxez).*(1-cxez1)+ei(cxez+1).*cxez1)*iez;
    zhy=permute(ae,[3,1,2]).*zhy-permute(be,[3,1,2]).*cat(3,diff(hy(:,:,1:na),1,3),diff(hy(:,:,end-na+1:end),1,3));
    xhy=permute(ae,[2,3,1]).*xhy-permute(be,[2,3,1]).*cat(1,diff(hy(1:na,:,:),1,1),diff(hy(end-na+1:end,:,:),1,1));
    hz=hz-s*(diff(ey(:,:,2:end-1),1,1)-diff(ex(:,:,2:end-1),1,2));
    hz([1:na,end-na+1:end],:,:)=hz([1:na,end-na+1:end],:,:)-s*xey;
    hz(:,[1:na,end-na+1:end],:)=hz(:,[1:na,end-na+1:end],:)+s*yex;
    hz([nc,end-nc+1],nc+1:end-nc,nc:end-nc+1)=hz([nc,end-nc+1],nc+1:end-nc,nc:end-nc+1)-s*permute([-1,1],[2,3,1]).*(ei(cxey).*(1-cxey1)+ei(cxey+1).*cxey1)*iey;
    hz(nc+1:end-nc,[nc,end-nc+1],nc:end-nc+1)=hz(nc+1:end-nc,[nc,end-nc+1],nc:end-nc+1)+s*permute([-1,1],[1,2,3]).*(ei(cyex).*(1-cyex1)+ei(cyex+1).*cyex1)*iex;
    xhz=permute(ae,[2,3,1]).*xhz-permute(be,[2,3,1]).*cat(1,diff(hz(1:na,:,:),1,1),diff(hz(end-na+1:end,:,:),1,1));
    yhz=permute(ae,[1,2,3]).*yhz-permute(be,[1,2,3]).*cat(2,diff(hz(:,1:na,:),1,2),diff(hz(:,end-na+1:end,:),1,2));
    ei(2:end-1)=ei(2:end-1)-s*diff(hi);
    ei(end-na+1:end-1)=ei(end-na+1:end-1)-s*zhi;
    zei=ami.*zei-bmi.*diff(ei(end-na:end));
    ei(1)=sin(2*pi*n*s/nd);
    ex(:,2:end-1,2:end-1)=ex(:,2:end-1,2:end-1)+s*(diff(hz,1,2)-diff(hy,1,3));
    ex(:,[2:na,end-na+1:end-1],2:end-1)=ex(:,[2:na,end-na+1:end-1],2:end-1)+s*yhz;
    ex(:,2:end-1,[2:na,end-na+1:end-1])=ex(:,2:end-1,[2:na,end-na+1:end-1])-s*zhy;
    ex(nc+1:end-nc,[nc+1,end-nc],nc+1:end-nc)=ex(nc+1:end-nc,[nc+1,end-nc],nc+1:end-nc)+s*permute([-1,1],[1,2,3]).*(hi(cyhz).*(1-cyhz1)+hi(cyhz+1).*cyhz1)*ihz;
    ex(nc+1:end-nc,nc+1:end-nc,[nc+1,end-nc])=ex(nc+1:end-nc,nc+1:end-nc,[nc+1,end-nc])-s*permute([-1,1],[3,1,2]).*(hi(czhy).*(1-czhy1)+hi(czhy+1).*czhy1)*ihy;
    ex(mask_ex)=0;
    yex=permute(am,[1,2,3]).*yex-permute(bm,[1,2,3]).*cat(2,diff(ex(:,1:na+1,2:end-1),1,2),diff(ex(:,end-na:end,2:end-1),1,2));
    zex=permute(am,[3,1,2]).*zex-permute(bm,[3,1,2]).*cat(3,diff(ex(:,2:end-1,1:na+1),1,3),diff(ex(:,2:end-1,end-na:end),1,3));
    ey(2:end-1,:,2:end-1)=ey(2:end-1,:,2:end-1)+s*(diff(hx,1,3)-diff(hz,1,1));
    ey(2:end-1,:,[2:na,end-na+1:end-1])=ey(2:end-1,:,[2:na,end-na+1:end-1])+s*zhx;
    ey([2:na,end-na+1:end-1],:,2:end-1)=ey([2:na,end-na+1:end-1],:,2:end-1)-s*xhz;
    ey(nc+1:end-nc,nc+1:end-nc,[nc+1,end-nc])=ey(nc+1:end-nc,nc+1:end-nc,[nc+1,end-nc])+s*permute([-1,1],[3,1,2]).*(hi(czhx).*(1-czhx1)+hi(czhx+1).*czhx1)*ihx;
    ey([nc+1,end-nc],nc+1:end-nc,nc+1:end-nc)=ey([nc+1,end-nc],nc+1:end-nc,nc+1:end-nc)-s*permute([-1,1],[2,3,1]).*(hi(cxhz).*(1-cxhz1)+hi(cxhz+1).*cxhz1)*ihz;
    ey(mask_ey)=0;
    zey=permute(am,[3,1,2]).*zey-permute(bm,[3,1,2]).*cat(3,diff(ey(2:end-1,:,1:na+1),1,3),diff(ey(2:end-1,:,end-na:end),1,3));
    xey=permute(am,[2,3,1]).*xey-permute(bm,[2,3,1]).*cat(1,diff(ey(1:na+1,:,2:end-1),1,1),diff(ey(end-na:end,:,2:end-1),1,1));
    ez(2:end-1,2:end-1,:)=ez(2:end-1,2:end-1,:)+s*(diff(hy,1,1)-diff(hx,1,2));
    ez([2:na,end-na+1:end-1],2:end-1,:)=ez([2:na,end-na+1:end-1],2:end-1,:)+s*xhy;
    ez(2:end-1,[2:na,end-na+1:end-1],:)=ez(2:end-1,[2:na,end-na+1:end-1],:)-s*yhx;
    ez([nc+1,end-nc],nc+1:end-nc,nc+1:end-nc)=ez([nc+1,end-nc],nc+1:end-nc,nc+1:end-nc)+s*permute([-1,1],[2,3,1]).*(hi(cxhy).*(1-cxhy1)+hi(cxhy+1).*cxhy1)*ihy;
    ez(nc+1:end-nc,[nc+1,end-nc],nc+1:end-nc)=ez(nc+1:end-nc,[nc+1,end-nc],nc+1:end-nc)-s*permute([-1,1],[1,2,3]).*(hi(cyhx).*(1-cyhx1)+hi(cyhx+1).*cyhx1)*ihx;
    ez(mask_ez)=0;
    xez=permute(am,[2,3,1]).*xez-permute(bm,[2,3,1]).*cat(1,diff(ez(1:na+1,2:end-1,:),1,1),diff(ez(end-na:end,2:end-1,:),1,1));
    yez=permute(am,[1,2,3]).*yez-permute(bm,[1,2,3]).*cat(2,diff(ez(2:end-1,1:na+1,:),1,2),diff(ez(2:end-1,end-na:end,:),1,2));
    set(hfig,'cdata',ez(:,:,nz/2+1));
    drawnow;
end
saveas(gcf,[mfilename,'.png']);
